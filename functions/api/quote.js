/**
 * Cloudflare Pages Function — POST /api/quote
 *
 * Environment variables (set in the Cloudflare Pages dashboard):
 *   RESEND_API_KEY     Resend API key (optional)
 *   QUOTE_TO_EMAIL     Destination inbox, e.g. AceBathroomRenovationsBrisbane@gmail.com
 *   QUOTE_FROM_EMAIL   Verified sender, e.g. website@acebathroomrenovationsbrisbane.com
 *   QUOTE_WEBHOOK_URL  Optional JSON webhook (Slack/Notion/Zapier/custom CRM)
 *
 * If no delivery channel is configured, the endpoint returns a clear phone/email
 * fallback instead of pretending the enquiry was delivered.
 */

const MAX_BODY_BYTES = 32 * 1024;
const PHONE_DISPLAY = "(07) 8590 6941";
const EMAIL = "AceBathroomRenovationsBrisbane@gmail.com";

const json = (data, status = 200) =>
  new Response(JSON.stringify(data), {
    status,
    headers: {
      "content-type": "application/json; charset=utf-8",
      "cache-control": "no-store",
      "x-content-type-options": "nosniff",
    },
  });

const clean = (value, max = 2000) =>
  String(value == null ? "" : value).replace(/\s+/g, " ").trim().slice(0, max);

const escapeHtml = (value) =>
  String(value == null ? "" : value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");

const isEmail = (value) => !value || /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(value);
const isPhone = (value) => /^[+()\d\s.-]{6,30}$/.test(value);

function fieldsFrom(form) {
  const get = (key, max) => clean(form.get(key), max);
  return {
    name: get("name", 80),
    phone: get("phone", 30),
    email: get("email", 120),
    suburb: get("suburb", 60),
    property: get("property", 80),
    project: get("project", 80),
    budget: get("budget", 80),
    timeline: get("timeline", 80),
    message: get("message", 2000),
    source: get("source", 60),
    consent: form.get("consent") === "yes" || form.get("consent") === "on",
    honeypot: get("company_website", 200),
  };
}

function validate(data) {
  const errors = [];
  if (data.name.length < 2) errors.push("Please enter your name.");
  if (!isPhone(data.phone)) errors.push("Please enter a valid phone number.");
  if (!isEmail(data.email)) errors.push("Please check the email address.");
  if (!data.suburb) errors.push("Please enter your suburb.");
  if (!data.message && data.source !== "quote-page") errors.push("Please tell us how we can help.");
  if (!data.consent) errors.push("Please confirm you agree to be contacted.");
  return errors;
}

function enquiryText(data) {
  return [
    `New website enquiry — ${data.source || "website"}`,
    "",
    `Name: ${data.name}`,
    `Phone: ${data.phone}`,
    `Email: ${data.email || "Not provided"}`,
    `Suburb: ${data.suburb}`,
    data.property ? `Property: ${data.property}` : "",
    data.project ? `Project: ${data.project}` : "",
    data.budget ? `Budget: ${data.budget}` : "",
    data.timeline ? `Timeline: ${data.timeline}` : "",
    "",
    "Message:",
    data.message || "(none)",
    "",
    `Received: ${new Date().toISOString()}`,
  ].filter(Boolean).join("\n");
}

function enquiryHtml(data) {
  const row = (label, value) =>
    value ? `<tr><th style="text-align:left;padding:6px 12px 6px 0;color:#4a6570;font-weight:600;vertical-align:top">${escapeHtml(label)}</th><td style="padding:6px 0">${escapeHtml(value)}</td></tr>` : "";
  return `<!doctype html><html><body style="font-family:Arial,sans-serif;color:#132e36;line-height:1.5">
  <h1 style="font-size:18px;color:#004155">New website enquiry</h1>
  <p style="color:#4a6570;font-size:13px">Source: ${escapeHtml(data.source || "website")} · ${escapeHtml(new Date().toLocaleString("en-AU", { timeZone: "Australia/Brisbane" }))}</p>
  <table style="border-collapse:collapse;font-size:14px">
    ${row("Name", data.name)}
    ${row("Phone", data.phone)}
    ${row("Email", data.email)}
    ${row("Suburb", data.suburb)}
    ${row("Property", data.property)}
    ${row("Project", data.project)}
    ${row("Budget", data.budget)}
    ${row("Timeline", data.timeline)}
  </table>
  <h2 style="font-size:14px;color:#004155;margin-top:20px">Message</h2>
  <p style="white-space:pre-wrap;font-size:14px;background:#f3f9ff;padding:12px;border-radius:6px">${escapeHtml(data.message || "(none)")}</p>
  <p style="font-size:12px;color:#6b8790">Reply directly to this email to contact the enquirer. This message was generated by the Ace Bathroom Renovations Brisbane website.</p>
  </body></html>`;
}

async function sendWithResend(env, data) {
  const apiKey = env.RESEND_API_KEY;
  const to = env.QUOTE_TO_EMAIL;
  const from = env.QUOTE_FROM_EMAIL;
  if (!apiKey || !to || !from) return { skipped: true };

  const payload = {
    from,
    to: [to],
    subject: `Website enquiry: ${data.name} — ${data.suburb}`,
    text: enquiryText(data),
    html: enquiryHtml(data),
  };
  if (data.email) payload.reply_to = data.email;

  const res = await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: {
      authorization: `Bearer ${apiKey}`,
      "content-type": "application/json",
    },
    body: JSON.stringify(payload),
  });
  if (!res.ok) {
    const detail = await res.text().catch(() => "");
    throw new Error(`Resend ${res.status}: ${detail.slice(0, 300)}`);
  }
  return { sent: true };
}

async function sendWebhook(env, data) {
  if (!env.QUOTE_WEBHOOK_URL) return { skipped: true };
  const res = await fetch(env.QUOTE_WEBHOOK_URL, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      type: "quote_enquiry",
      site: "acebathroomrenovationsbrisbane.com",
      receivedAt: new Date().toISOString(),
      ...data,
      honeypot: undefined,
    }),
  });
  if (!res.ok) throw new Error(`Webhook ${res.status}`);
  return { sent: true };
}

async function handlePost(context) {
  const { request, env } = context;

  const length = Number(request.headers.get("content-length") || 0);
  if (length > MAX_BODY_BYTES) {
    return json({ ok: false, message: `That enquiry is too large. Please call ${PHONE_DISPLAY}.` }, 413);
  }

  let form;
  try {
    form = await request.formData();
  } catch {
    return json({ ok: false, message: `We could not read that submission. Please call ${PHONE_DISPLAY}.` }, 400);
  }

  const data = fieldsFrom(form);

  // Honeypot: silently accept so bots do not learn the rule.
  if (data.honeypot) return json({ ok: true, message: "Thank you." });

  const errors = validate(data);
  if (errors.length) {
    return json({ ok: false, message: errors[0] }, 422);
  }

  const configured = Boolean(env.RESEND_API_KEY && env.QUOTE_TO_EMAIL && env.QUOTE_FROM_EMAIL) || Boolean(env.QUOTE_WEBHOOK_URL);
  if (!configured) {
    return json(
      {
        ok: false,
        message: `The online form is not connected right now. Please call ${PHONE_DISPLAY} or email ${EMAIL} and we will respond personally.`,
        fallback: { phone: PHONE_DISPLAY, email: EMAIL },
      },
      503
    );
  }

  const results = await Promise.allSettled([sendWithResend(env, data), sendWebhook(env, data)]);
  const delivered = results.some((r) => r.status === "fulfilled" && r.value && r.value.sent);

  if (!delivered) {
    for (const result of results) {
      if (result.status === "rejected") console.error("Quote delivery failed:", result.reason);
    }
    return json(
      {
        ok: false,
        message: `We could not deliver the form from this device. Please call ${PHONE_DISPLAY} or email ${EMAIL} so your enquiry is not delayed.`,
        fallback: { phone: PHONE_DISPLAY, email: EMAIL },
      },
      502
    );
  }

  return json({
    ok: true,
    message: `Thanks ${data.name.split(" ")[0]} — your enquiry has been received. We will call you on ${data.phone} during opening hours, 7am–10pm, seven days. If it is urgent, call ${PHONE_DISPLAY}.`,
  });
}

async function handleGet() {
  return json({ ok: false, message: "Use the quote form to submit an enquiry." }, 405);
}

export async function onRequest(context) {
  if (context.request.method === "POST") return handlePost(context);
  if (context.request.method === "GET" || context.request.method === "HEAD") return handleGet();
  return json({ ok: false, message: "Method not allowed." }, 405);
}

