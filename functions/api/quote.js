import { parseTrackingContext, saveSubmittedLead, updateLeadDelivery } from "../_lib/tracking.js";

/**
 * Cloudflare Pages Function — POST /api/quote
 *
 * Required Cloudflare Pages environment variable:
 *   QUOTE_WEBHOOK_URL  Google Apps Script Web App URL with its shared token
 *
 * Google Apps Script is the only production email route. If it is missing or
 * rejects a submission, the endpoint returns an error rather than falling back
 * to a different mail provider or claiming that the enquiry was delivered.
 */

const MAX_BODY_BYTES = 32 * 1024;
const PHONE_DISPLAY = "(07) 8590 6941";
const EMAIL = "AceBathroomRenovationsBrisbane@gmail.com";

const json = (data, status = 200) =>
  new Response(JSON.stringify(data), {
    status,
    headers: {
      "content-type": "application/json; charset=utf-8",
      "cache-control": "no-store",
      "x-content-type-options": "nosniff",
    },
  });

const clean = (value, max = 2000) =>
  String(value == null ? "" : value).replace(/\s+/g, " ").trim().slice(0, max);

const escapeHtml = (value) =>
  String(value == null ? "" : value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");

const isEmail = (value) => !value || /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(value);
const isPhone = (value) => /^[+()\d\s.-]{6,30}$/.test(value);

function fieldsFrom(form) {
  const get = (key, max) => clean(form.get(key), max);
  return {
    name: get("name", 80),
    phone: get("phone", 30),
    email: get("email", 120),
    suburb: get("suburb", 60),
    property: get("property", 80),
    project: get("project", 80),
    budget: get("budget", 80),
    timeline: get("timeline", 80),
    message: get("message", 2000),
    source: get("source", 60),
    formType: get("form_type", 40),
    leadId: get("lead_id", 36),
    trackingContext: String(form.get("tracking_context") || "").slice(0, 12000),
    consent: form.get("consent") === "yes" || form.get("consent") === "on",
    honeypot: get("ax_hp", 200) || get("company_website", 200),
  };
}

function validate(data) {
  const errors = [];
  if (data.name.length < 2) errors.push("Please enter your name.");
  if (!isPhone(data.phone)) errors.push("Please enter a valid phone number.");
  if (!isEmail(data.email)) errors.push("Please check the email address.");
  if (!data.suburb) errors.push("Please enter your suburb.");
  if (!data.message && data.source !== "quote-page") errors.push("Please tell us how we can help.");
  if (!data.consent) errors.push("Please confirm you agree to be contacted.");
  return errors;
}

function enquiryText(data) {
  return [
    `New website enquiry — ${data.source || "website"}`,
    "",
    `Name: ${data.name}`,
    `Phone: ${data.phone}`,
    `Email: ${data.email || "Not provided"}`,
    `Suburb: ${data.suburb}`,
    data.property ? `Property: ${data.property}` : "",
    data.project ? `Project: ${data.project}` : "",
    data.budget ? `Budget: ${data.budget}` : "",
    data.timeline ? `Timeline: ${data.timeline}` : "",
    "",
    "Message:",
    data.message || "(none)",
    "",
    `Received: ${new Date().toISOString()}`,
  ].filter(Boolean).join("\n");
}

