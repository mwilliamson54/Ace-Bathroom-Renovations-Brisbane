async function sendWebhook(env, data, ipAddress) {
  if (!env.QUOTE_WEBHOOK_URL) return { skipped: true };
  // Only pass the enquiry fields needed by the relay. Visitor IDs, session IDs
  // and campaign attribution remain in Supabase and are not sent to Apps Script.
  const {
    leadId: _leadId,
    trackingContext: _trackingContext,
    ...enquiry
  } = data;
  const res = await fetch(env.QUOTE_WEBHOOK_URL, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      type: "quote_enquiry",
      site: "acebathroomrenovationsbrisbane.com",
      receivedAt: new Date().toISOString(),
      ...enquiry,
      ipAddress: clean(ipAddress, 45),
      honeypot: undefined,
    }),
  });
  const text = await res.text().catch(() => "");
  if (!res.ok) throw new Error(`Webhook ${res.status}: ${text.slice(0, 200)}`);

  // Google Apps Script always answers 200, even when it rejected the submission
  // (bad token, mail quota, script error). Treat ok:false as a failed channel so
  // the form does not report "delivered" for a lead nobody received.
  if (text) {
    try {
      const body = JSON.parse(text);
      if (body && body.ok === false) {
        throw new Error(`Webhook rejected: ${String(body.error || "unknown").slice(0, 200)}`);
      }
    } catch (error) {
      if (error instanceof SyntaxError) return { sent: true };
      throw error;
    }
  }
  return { sent: true };
}

async function record(env, entry) {
  if (!env || !env.QUOTE_LOG) return;
  try {
    const key = `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
    await env.QUOTE_LOG.put(key, JSON.stringify(entry), { expirationTtl: 60 * 60 * 24 * 90 });
  } catch (error) {
    console.error("Quote log write failed:", error && error.message);
  }
}

async function handlePost(context) {
  const { request, env } = context;

  const length = Number(request.headers.get("content-length") || 0);
  if (length > MAX_BODY_BYTES) {
    return json({ ok: false, message: `That enquiry is too large. Please call ${PHONE_DISPLAY}.` }, 413);
  }

  let form;
  try {
    form = await request.formData();
  } catch {
    await record(env, {
      at: new Date().toISOString(),
      outcome: "unreadable_body",
      contentType: request.headers.get("content-type") || "",
      contentLength: length,
    });
    return json({ ok: false, message: `We could not read that submission. Please call ${PHONE_DISPLAY}.` }, 400);
  }

  const data = fieldsFrom(form);
  const trackingContext = parseTrackingContext(data.trackingContext, request);
  let trackingLeadId = "";

  // Diagnostic trail. Deliberately logs no names, phone numbers, emails or message
  // bodies: only field presence and the delivery outcome.
  const trace = {
    event: "quote_received",
    source: data.source || "website",
    fields: Object.keys(Object.fromEntries(form.entries())).length,
    hasName: data.name.length > 0,
    hasPhone: data.phone.length > 0,
    hasSuburb: data.suburb.length > 0,
    hasMessage: data.message.length > 0,
    honeypotHit: Boolean(data.honeypot),
    consent: data.consent,
  };

  // Every submission is archived to KV before responding, so a lead is never lost
  // even if delivery fails, and so the exact fields the browser sent can be inspected.
  const finish = async (response, outcome, extra = {}) => {
    await record(env, {
      at: new Date().toISOString(),
      outcome,
      ...data,
      honeypotHit: Boolean(data.honeypot),
      // Enough request metadata to tell one visitor's browser from a script test.
      ua: clean(request.headers.get("user-agent"), 160),
      referer: clean(request.headers.get("referer"), 160),
      country: (request.cf && request.cf.country) || "",
      ...extra,
    });
    if (trackingLeadId) {
      const deliveryStatus = outcome === "delivered" ? "delivered" :
        outcome === "not_configured" ? "not_configured" : "failed";
      try {
        await updateLeadDelivery(
          env, trackingLeadId, trackingContext && trackingContext.visitor_id,
          deliveryStatus, extra.deliveryError || "", extra.resendId || ""
        );
      } catch (error) {
        console.error("Supabase delivery status update failed:", error && error.message);
      }
    }
    return response;
  };

  // Honeypot: bots fill hidden fields. Browser autofill occasionally does too, so a
  // submission that otherwise looks like a genuine enquiry is delivered and flagged
  // rather than being silently discarded.
  if (data.honeypot) {
    const genuine = validate(data).length === 0;
    if (!genuine) {
      console.warn(JSON.stringify({ ...trace, event: "quote_honeypot_blocked" }));
      return finish(json({ ok: true, message: "Thank you." }), "blocked_honeypot");
    }
    console.warn(JSON.stringify({ ...trace, event: "quote_honeypot_flagged" }));
    data.subjectPrefix = "[check honeypot] ";
  }

  const errors = validate(data);
  if (errors.length) {
    console.warn(JSON.stringify({ ...trace, event: "quote_invalid", error: errors[0] }));
    return finish(json({ ok: false, message: errors[0] }, 422), "invalid", { error: errors[0] });
  }

  // The visitor-facing response must not wait for Supabase, Apps Script or KV.
  // Pages Functions waitUntil keeps those tasks running after we return 202.
  if (!env.QUOTE_WEBHOOK_URL) {
    return finish(
      json(
        {
          ok: false,
          message: `The online form is not connected right now. Please call ${PHONE_DISPLAY} or email ${EMAIL} and we will respond personally.`,
          fallback: { phone: PHONE_DISPLAY, email: EMAIL },
        },
        503
      ),
      "not_configured"
    );
  }

  const response = json({
    ok: true,
    accepted: true,
    status: "processing",
    message: `Thanks ${data.name.split(" ")[0]} — we have received your enquiry. Our team will contact you shortly.`,
    lead_id: data.leadId || null,
  }, 202);

  const backgroundTask = processAcceptedSubmission(context, data, trackingContext, trace)
    .catch((error) => {
      // Never let a background failure change the already-sent visitor response.
      console.error("Background quote processing failed:", error && error.message);
    });

  // Cloudflare Pages Functions provide waitUntil on the request context.
  // In local/test contexts without it, await the task so errors remain observable.
  if (typeof context.waitUntil === "function") {
    context.waitUntil(backgroundTask);
    return response;
  }

  await backgroundTask;
  return response;
}

async function processAcceptedSubmission(context, data, trackingContext, trace) {
  const { request, env } = context;
  let trackingLeadId = "";

  try {
    trackingLeadId = await saveSubmittedLead(env, {
      lead_id: data.leadId,
      tracking_context: data.trackingContext,
      source: data.source,
      form_type: data.formType || (data.source === "contact-page" ? "contact" : "quote"),
      name: data.name,
      phone: data.phone,
      email: data.email,
      suburb: data.suburb,
      property: data.property,
      project: data.project,
      budget: data.budget,
      timeline: data.timeline,
      message: data.message,
      consent: data.consent,
    }, request);
  } catch (error) {
    console.error("Supabase lead save failed:", error && error.message);
  }

  let delivered = false;
  let deliveryError = "";
  try {
    const result = await sendWebhook(env, data, trackingContext && trackingContext.ip_address);
    delivered = Boolean(result && result.sent);
  } catch (error) {
    deliveryError = String((error && error.message) || error).slice(0, 300);
    console.error("Google Apps Script delivery failed:", deliveryError);
  }

  const outcome = delivered ? "delivered" : "undelivered";
  await record(env, {
    at: new Date().toISOString(),
    outcome,
    ...data,
    honeypotHit: Boolean(data.honeypot),
    ua: clean(request.headers.get("user-agent"), 160),
    referer: clean(request.headers.get("referer"), 160),
    country: (request.cf && request.cf.country) || "",
    deliveryError,
  });

  if (trackingLeadId) {
    try {
      await updateLeadDelivery(
        env,
        trackingLeadId,
        trackingContext && trackingContext.visitor_id,
        delivered ? "delivered" : "failed",
        deliveryError,
        ""
      );
    } catch (error) {
      console.error("Supabase delivery status update failed:", error && error.message);
    }
  }

  if (delivered) {
    console.log(JSON.stringify({ ...trace, event: "quote_delivered" }));
  } else {
    console.error(JSON.stringify({ ...trace, event: "quote_undelivered" }));
  }
}


async function handleGet() {
  return json({ ok: false, message: "Use the quote form to submit an enquiry." }, 405);
}

export async function onRequest(context) {
  if (context.request.method === "POST") return handlePost(context);
  if (context.request.method === "GET" || context.request.method === "HEAD") return handleGet();
  return json({ ok: false, message: "Method not allowed." }, 405);
}

